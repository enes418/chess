export function getDailyPuzzle(): ChessPuzzle {
  const now = new Date();
  const daySeed =
    now.getUTCFullYear() * 10000 + (now.getUTCMonth() + 1) * 100 + now.getUTCDate();
  return CHESS_PUZZLES[daySeed % CHESS_PUZZLES.length];
}
